"""
Convert the official IAGA IGRF coefficient table (``igrf<N>coeffs.txt``) into
the two formats gtracr reads:

- ``IGRF<N>.COF`` (geomag70 format), converted further to ``igrf<N>.json`` by
  ``cof_to_json.py`` for the C++ ``IGRF`` class;
- ``IGRF<N>.shc`` (spherical-harmonic coefficient format) for the Python
  ``gtracr.bfield.IGRF`` class. Its last column is the final main-field
  epoch advanced by five years of secular variation, as in the IAGA files.

Run this, then ``cof_to_json.py``, whenever a new IGRF generation is released.
The table is available from https://www.ncei.noaa.gov/products/international-geomagnetic-reference-field
(``igrf14coeffs.txt``: https://www.ngdc.noaa.gov/IAGA/vmod/coeffs/igrf14coeffs.txt).
"""

import os

IGRF_VERSION = 14  # should be updated with each IGRF version

CURRENT_DIR = os.path.dirname(os.path.realpath(__file__))
DATA_DIR = os.path.join(os.path.dirname(CURRENT_DIR), "data")
TXT_PATH = os.path.join(DATA_DIR, f"igrf{IGRF_VERSION}coeffs.txt")
COF_PATH = os.path.join(DATA_DIR, f"IGRF{IGRF_VERSION}.COF")
SHC_PATH = os.path.join(DATA_DIR, f"IGRF{IGRF_VERSION}.shc")

ALTMIN, ALTMAX = -1.0, 600.0  # validity altitudes written by geomag70 (km)


def read_table(path):
    """Return (kinds, epochs, rows) of the IAGA table.

    kinds[i] is "IGRF"/"DGRF" of epoch column i; the last data column is the
    secular variation of the final epoch. rows: list of (gh, n, m, values).
    """
    with open(path) as f:
        lines = [
            line.split() for line in f if line.strip() and not line.startswith("#")
        ]
    kinds = lines[0][3:]
    epochs = [float(e) for e in lines[1][3:-1]]  # last header is "2025-30"
    assert kinds[-1] == "SV" and len(kinds) == len(epochs) + 1
    rows = [
        (g, int(n), int(m), [float(v) for v in vals]) for g, n, m, *vals in lines[2:]
    ]
    return kinds[:-1], epochs, rows


def coefficients(rows, n_epochs):
    """{(n, m): [(g, h) per epoch], ...} and {(n, m): (gdot, hdot)}."""
    gh = {}
    sv = {}
    for g_or_h, n, m, vals in rows:
        main, dot = vals[:n_epochs], vals[n_epochs]
        entry = gh.setdefault((n, m), [[0.0, 0.0] for _ in range(n_epochs)])
        dots = sv.setdefault((n, m), [0.0, 0.0])
        idx = 0 if g_or_h == "g" else 1
        for i, v in enumerate(main):
            entry[i][idx] = v
        dots[idx] = dot
    return gh, sv


def max_degree(gh, i):
    """Highest degree with a non-zero coefficient in epoch i."""
    return max(n for (n, m), vals in gh.items() if any(vals[i]))


def model_name(kind, epoch):
    year = int(epoch)
    return f"{kind}{year % 100:02d}" if year < 2000 else f"{kind}{year}"


def write_cof(kinds, epochs, gh, sv):
    nm = sorted(gh)
    sv_deg = max(n for (n, m), d in sv.items() if any(d))
    out = []
    for i, (kind, epoch) in enumerate(zip(kinds, epochs)):
        last = i == len(epochs) - 1
        name = model_name(kind, epoch)
        nmain = max_degree(gh, i)
        nsv = sv_deg if last else 0
        out.append(
            f"{name:>11s}{epoch:9.2f}{nmain:3d}{nsv:3d}{0:3d}{epoch:8.2f}{epoch + 5:8.2f}"
            f"{ALTMIN:7.1f}{ALTMAX:7.1f}{name:>19s}{0:4d}"
        )
        line_num = 0
        for n, m in nm:
            if n > nmain:
                continue
            line_num += 1
            g, h = gh[(n, m)][i]
            gdot, hdot = sv[(n, m)] if last and n <= nsv else (0.0, 0.0)
            out.append(
                f"{n:2d}{m:3d}{g:10.2f}{h:10.2f}{gdot:10.2f}{hdot:10.2f}{name:>33s}{line_num:4d}"
            )
    with open(COF_PATH, "w") as f:
        f.write("\n".join(out) + "\n")


def write_shc(epochs, gh, sv):
    times = epochs + [epochs[-1] + 5.0]
    nmax = max(n for n, m in gh)
    out = [
        f"# IGRF {IGRF_VERSION}",
        f"# International Geomagnetic Reference Field -- {IGRF_VERSION}th generation",
        "# generated by gtracr/scripts/igrf_txt_to_cof_shc.py from "
        f"igrf{IGRF_VERSION}coeffs.txt (IAGA)",
        f"1  {nmax} {len(times)} 2 1 {times[0]:.1f} {times[-1]:.1f}",
        "      " + " ".join(f"{t:.1f}" for t in times),
    ]

    def fmt(vals):
        return " ".join(f"{v:.10g}" for v in vals)

    for n, m in sorted(gh):
        g = [vals[0] for vals in gh[(n, m)]]
        g.append(round(g[-1] + 5.0 * sv[(n, m)][0], 4))
        out.append(f"{n:2d} {m:3d} {fmt(g)}")
        if m > 0:
            h = [vals[1] for vals in gh[(n, m)]]
            h.append(round(h[-1] + 5.0 * sv[(n, m)][1], 4))
            out.append(f"{n:2d} {-m:3d} {fmt(h)}")
    with open(SHC_PATH, "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    kinds, epochs, rows = read_table(TXT_PATH)
    gh, sv = coefficients(rows, len(epochs))
    write_cof(kinds, epochs, gh, sv)
    write_shc(epochs, gh, sv)
